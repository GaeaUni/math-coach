/** 展开成 [{ c, text, g, grp }]，text 里的 {字} 是答案位置 */
export function tongyinItems(list = TONGYIN) {
  const out = [];
  for (const grp of list) for (const text of grp.s) out.push({ c: text.match(/\{(.)\}/)[1], text, g: grp.g, grp });
  return out;
}
