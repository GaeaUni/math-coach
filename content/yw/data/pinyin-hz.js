function parseBH(s) {
  return s.trim().split('\n').map((line) => {
    const [ch, ...rest] = line.trim().split(/\s+/);
    const unsure = rest.map((n) => n.endsWith('?'));
    return { ch, names: rest.map((n) => n.replace('?', '')), unsure, sure: !unsure.some(Boolean) };
  });
}
