for (const line of ZI_RAW.trim().split('\n')) {
  const [c, n, st, parts, bs, order] = line.split(' ');
  const d = (x) => (x === '-' ? null : x);
  ZI[c] = { n: +n, st: d(st), parts: parts === '-' ? null : [...parts], bs: d(bs), order: d(order) };
}

const SHOW = (p) => (p === '⺮' ? '竹字头' : `「${p}」`);
/** 一个字的字形：{ n 笔画数, st 结构, parts 部件, bs 部首, order 笔顺要点（一句话） }，没有的项是 null */
export function zixing(c) {
  const z = ZI[c];
  if (!z) return null;
  let order = null;
  if (z.parts && z.order) {
    const [a, b, c3] = z.parts.map(SHOW);
    order = {
      lr: `先写左边${a}，再写右边${b}`,
      tb: `先写上面${a}，再写下面${b}`,
      lmr: `从左到右：${a}、${b}、${c3}`,
      tmb: `从上到下：${a}、${b}、${c3}`,
      qw: `先外后内再封口：先写外框的竖和横折，再写里面的${b}，最后写底下一横封口`,
      zou: `先写里面的${b}，最后写走之`,
      jian: `先写里面的${b}，最后写建之旁`,
      nw: `先里后外：先写里面的${b}，再写${a}`,
      kuang: `先写上面的横，再写里面的${b}，最后写左下的竖折`,
      wn: `先外后内：先写${a}，再写里面的${b}`,
      pin: '先写上面，再写下面，下面先左后右',
    }[z.order] || null;
  }
  return { n: z.n, st: z.st, parts: z.parts, bs: z.bs, order };
}
