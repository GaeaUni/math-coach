/** 把 w 展开成 [{ c, py, word, g }] */
export function duoyinWords(list = DUOYIN) {
  const out = [];
  for (const d of list) {
    for (const [py, s] of Object.entries(d.w)) {
      for (const tok of s.split(/\s+/)) {
        const m = tok.match(/^(.+?)(\d)$/);
        out.push({ c: d.c, py, word: m[1], g: +m[2], d });
      }
    }
  }
  return out;
}
